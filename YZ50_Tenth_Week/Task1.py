import torch
from transformers import GPT2LMHeadModel
import matplotlib.pyplot as plt


if __name__ == '__main__':
    
    model_hf = GPT2LMHeadModel.from_pretrained("gpt2")  # 124M
    sd_hf = model_hf.state_dict()

    for k, v in sd_hf.items():
        print(k, v.shape)
    print(f"Total parameters: {sum(v.numel() for v in sd_hf.values()):,}")

    wpe = sd_hf["transformer.wpe.weight"]

    # 1. Save heatmap of position embeddings
    plt.figure(figsize=(10, 6))
    plt.imshow(wpe, cmap="gray")
    plt.title("transformer.wpe.weight heatmap")
    plt.xlabel("Embedding Channel")
    plt.ylabel("Position")
    plt.colorbar()
    plt.savefig("wpe_heatmap.png", bbox_inches="tight")
    plt.close()

    # 2. Save line plots across positions for channels 150, 200, 250
    plt.figure(figsize=(10, 6))
    plt.plot(wpe[:, 150], label="channel 150")
    plt.plot(wpe[:, 200], label="channel 200")
    plt.plot(wpe[:, 250], label="channel 250")
    plt.title("WPE across positions for selected channels")
    plt.xlabel("Position")
    plt.ylabel("Value")
    plt.legend()
    plt.savefig("wpe_channels.png", bbox_inches="tight")
    plt.close()

